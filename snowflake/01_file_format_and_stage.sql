CREATE FILE FORMAT IF NOT EXISTS RAW.DLD.FF_CSV_HEADER
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  TRIM_SPACE = TRUE
  ENCODING = 'UTF8'
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE STAGE IF NOT EXISTS RAW.DLD.DLD_STAGE
  FILE_FORMAT = RAW.DLD.FF_CSV_HEADER
  COMMENT = 'Landing area for DLD CSV files';
